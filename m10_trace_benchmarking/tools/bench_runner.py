#!/usr/bin/env python3
"""
bench_runner.py — Benchmarks NoC router designs using trace replays.

Loads a JSON trace generated by trace_gen.py, dynamically constructs a
SystemVerilog testbench to replay the trace cycle-by-cycle against wh_mesh,
runs Icarus Verilog simulation, extracts latency and throughput metrics,
and saves the per-packet and summary results to CSV.
"""

import argparse
import csv
import json
import os
import subprocess
import sys


def parse_args():
    parser = argparse.ArgumentParser(description="Run NoC trace benchmark simulation.")
    parser.add_argument("--trace", type=str, required=True, help="Path to input trace JSON")
    parser.add_argument("--out_csv", type=str, default="results/bench_results.csv",
                        help="Path for detailed per-packet results CSV")
    parser.add_argument("--summary_csv", type=str, default="results/bench_summary.csv",
                        help="Path for overall summary metrics CSV")
    parser.add_argument("--max_wait", type=int, default=300,
                        help="Extra drain cycles after last injected packet")
    parser.add_argument("--vcs_per_vn", type=int, default=2, help="VCs per virtual network")
    parser.add_argument("--buffer_depth", type=int, default=4, help="FIFO depth per VC")
    parser.add_argument("--sim_only", action="store_true", help="Only run simulation if TB already built")
    return parser.parse_args()


def generate_tb(trace_path, tb_path, vcs_per_vn, buffer_depth, max_wait):
    with open(trace_path, "r") as f:
        data = json.load(f)

    cfg = data["config"]
    packets = data["packets"]
    mesh_w = cfg["mesh_w"]
    mesh_h = cfg["mesh_h"]
    num_tiles = mesh_w * mesh_h
    total_cycles = cfg["cycles"] + max_wait

    # Group packets by injection cycle
    cycle_pkts = {}
    for pkt in packets:
        c = pkt["cycle"]
        cycle_pkts.setdefault(c, []).append(pkt)

    tb_code = f"""`timescale 1ns/1ps
// Auto-generated trace replay testbench by bench_runner.py
import noc_pkg::*;
import wh_pkg::*;

module trace_replay_tb;

  localparam int MESH_W       = {mesh_w};
  localparam int MESH_H       = {mesh_h};
  localparam int NUM_TILES    = {num_tiles};
  localparam int NUM_VNS      = 1;
  localparam int VCS_PER_VN   = {vcs_per_vn};
  localparam int NUM_VCS      = NUM_VNS * VCS_PER_VN;
  localparam int BUFFER_DEPTH = {buffer_depth};

  logic clk = 0;
  logic rst_n;
  always #5 clk = ~clk;

  logic     [NUM_TILES-1:0]          local_in_valid;
  logic     [NUM_TILES*VC_W-1:0]     local_in_vc;
  wh_flit_t [NUM_TILES-1:0]          local_in_data;
  logic     [NUM_TILES*NUM_VCS-1:0]  local_in_credit_return;

  logic     [NUM_TILES-1:0]          local_out_valid;
  logic     [NUM_TILES*VC_W-1:0]     local_out_vc;
  wh_flit_t [NUM_TILES-1:0]          local_out_data;
  logic     [NUM_TILES*NUM_VCS-1:0]  local_out_credit_return;
  logic     [NUM_TILES*3-1:0]        tile_alarm;

  wh_mesh #(
    .MESH_W(MESH_W), .MESH_H(MESH_H),
    .NUM_VNS(NUM_VNS), .VCS_PER_VN(VCS_PER_VN),
    .BUFFER_DEPTH(BUFFER_DEPTH), .SA_ITERS(1),
    .SECURE(0), .PIPE(0)
  ) dut (
    .clk(clk), .rst_n(rst_n),
    .local_in_valid(local_in_valid), .local_in_vc(local_in_vc),
    .local_in_data(local_in_data), .local_in_credit_return(local_in_credit_return),
    .local_out_valid(local_out_valid), .local_out_vc(local_out_vc),
    .local_out_data(local_out_data), .local_out_credit_return(local_out_credit_return),
    .tile_alarm(tile_alarm)
  );

  function automatic wh_flit_t mk_wh_flit(
    input flit_type_e ft,
    input int sx, input int sy,
    input int dx, input int dy,
    input int pay
  );
    mk_wh_flit.flit_type = ft;
    mk_wh_flit.mclass    = 2'd0;
    mk_wh_flit.src_x     = sx[COORD_WIDTH-1:0];
    mk_wh_flit.src_y     = sy[COORD_WIDTH-1:0];
    mk_wh_flit.dest_x    = dx[COORD_WIDTH-1:0];
    mk_wh_flit.dest_y    = dy[COORD_WIDTH-1:0];
    mk_wh_flit.payload   = pay[15:0];
  endfunction

  // Return credit immediately when flit is received
  genvar gt, gv;
  generate
    for (gt = 0; gt < NUM_TILES; gt++) begin : g_recvr
      for (gv = 0; gv < NUM_VCS; gv++) begin : g_recvr_vc
        always_ff @(posedge clk or negedge rst_n) begin
          if (!rst_n) local_out_credit_return[gt*NUM_VCS + gv] <= 1'b0;
          else begin
            if (local_out_valid[gt] && (local_out_vc[gt*VC_W +: VC_W] == gv))
              local_out_credit_return[gt*NUM_VCS + gv] <= 1'b1;
            else
              local_out_credit_return[gt*NUM_VCS + gv] <= 1'b0;
          end
        end
      end
    end
  endgenerate

  int sim_cycle = 0;
  always @(posedge clk) begin
    if (rst_n) sim_cycle <= sim_cycle + 1;
  end

  // Monitor ejections and print CSV-formatted events
  always @(posedge clk) begin
    if (rst_n) begin
      for (int t = 0; t < NUM_TILES; t++) begin
        if (local_out_valid[t]) begin
          int pid;
          flit_type_e ft;
          wh_flit_t f_out;
          f_out = local_out_data[t];
          pid   = f_out.payload[13:0];
          ft    = f_out.flit_type;
          $display("EJECT: cycle=%0d tile=%0d pid=%0d flit_type=%0d src_x=%0d src_y=%0d dst_x=%0d dst_y=%0d",
                   sim_cycle, t, pid, ft,
                   f_out.src_x, f_out.src_y,
                   f_out.dest_x, f_out.dest_y);
        end
      end
    end
  end

  wh_flit_t f;

  // Injection stimulus process
  initial begin
    local_in_valid = '0;
    local_in_vc    = '0;
    local_in_data  = '0;

    rst_n = 0;
    repeat (5) @(posedge clk);
    rst_n = 1;
    repeat (2) @(posedge clk);
"""

    # Inject stimulus
    for cycle in sorted(cycle_pkts.keys()):
        tb_code += f"    // Cycle {cycle}\n"
        tb_code += f"    while (sim_cycle < {cycle}) @(posedge clk);\n"
        for p in cycle_pkts[cycle]:
            s_tile = p["src_tile"]
            pid = p["pkt_id"]
            num_flits = p["num_flits"]
            src_x = p["src_x"]
            src_y = p["src_y"]
            dest_x = p["dest_x"]
            dest_y = p["dest_y"]

            for f_idx in range(num_flits):
                if num_flits == 1:
                    ftype = "FT_SINGLE"
                elif f_idx == 0:
                    ftype = "FT_HEAD"
                elif f_idx == num_flits - 1:
                    ftype = "FT_TAIL"
                else:
                    ftype = "FT_BODY"

                tb_code += f"""    f = mk_wh_flit({ftype}, {src_x}, {src_y}, {dest_x}, {dest_y}, {pid});
    local_in_valid[{s_tile}] = 1'b1;
    local_in_vc[{s_tile}*VC_W +: VC_W] = 0;
    local_in_data[{s_tile}] = f;
    $display("INJECT: cycle=%0d tile={s_tile} pid={pid} flit_idx={f_idx} flit_type={ftype}", sim_cycle);
    @(posedge clk);
    local_in_valid[{s_tile}] = 1'b0;
"""

    tb_code += f"""
    // Drain network
    repeat ({max_wait}) @(posedge clk);
    $display("SIMULATION_COMPLETE: final_cycle=%0d", sim_cycle);
    $finish;
  end

endmodule : trace_replay_tb
"""

    with open(tb_path, "w") as f:
        f.write(tb_code)

    return total_cycles


def run_benchmark(trace_path, out_csv, summary_csv, vcs_per_vn, buffer_depth, max_wait):
    REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    os.makedirs(os.path.dirname(out_csv) or ".", exist_ok=True)
    tb_path = os.path.join(REPO_ROOT, "m10_trace_benchmarking", "tb", "trace_replay_tb.sv")
    os.makedirs(os.path.dirname(tb_path), exist_ok=True)

    print(f"Generating testbench from trace: {trace_path}...")
    generate_tb(trace_path, tb_path, vcs_per_vn, buffer_depth, max_wait)

    with open(trace_path, "r") as f:
        tdata = json.load(f)
    cfg = tdata["config"]
    pkts = {p["pkt_id"]: p for p in tdata["packets"]}

    # Compile with iverilog
    vvp_bin = os.path.join(REPO_ROOT, "m10_trace_benchmarking", "sim", "trace_replay.vvp")
    os.makedirs(os.path.dirname(vvp_bin), exist_ok=True)

    cmd_compile = [
        "iverilog", "-g2012", "-Wall", "-o", vvp_bin,
        os.path.join(REPO_ROOT, "m8_pipeline/rtl/noc_pkg.sv"),
        os.path.join(REPO_ROOT, "m8_pipeline/rtl/rr_arbiter.sv"),
        os.path.join(REPO_ROOT, "m8_pipeline/rtl/flit_fifo.sv"),
        os.path.join(REPO_ROOT, "m8_pipeline/rtl/vc_router.sv"),
        os.path.join(REPO_ROOT, "m9_wormhole_switching/rtl/wh_pkg.sv"),
        os.path.join(REPO_ROOT, "m9_wormhole_switching/rtl/wh_vc_reservation.sv"),
        os.path.join(REPO_ROOT, "m9_wormhole_switching/rtl/wh_router.sv"),
        os.path.join(REPO_ROOT, "m9_wormhole_switching/rtl/wh_mesh.sv"),
        tb_path
    ]

    print("Compiling SystemVerilog simulation...")
    res = subprocess.run(cmd_compile, capture_output=True, text=True)
    if res.returncode != 0:
        print("Compilation failed:\n", res.stderr)
        return False

    print("Running simulation...")
    sim_res = subprocess.run(["vvp", vvp_bin], capture_output=True, text=True)
    if sim_res.returncode != 0:
        print("Simulation runtime error:\n", sim_res.stderr)
        return False

    # Parse simulation output
    inject_times = {}  # pid -> first inject cycle
    eject_times = {}   # pid -> last eject cycle
    flits_rcvd = {}    # pid -> count

    for line in sim_res.stdout.splitlines():
        if line.startswith("INJECT:"):
            # INJECT: cycle=10 tile=0 pid=2 flit_idx=0 flit_type=FT_HEAD
            parts = dict(kv.split("=") for kv in line.split()[1:] if "=" in kv)
            pid = int(parts["pid"])
            cyc = int(parts["cycle"])
            if pid not in inject_times:
                inject_times[pid] = cyc
        elif line.startswith("EJECT:"):
            # EJECT: cycle=14 tile=8 pid=2 flit_type=3 ...
            parts = dict(kv.split("=") for kv in line.split()[1:] if "=" in kv)
            pid = int(parts["pid"])
            cyc = int(parts["cycle"])
            flits_rcvd[pid] = flits_rcvd.get(pid, 0) + 1
            eject_times[pid] = cyc  # updates until tail

    # Write detailed CSV
    results_rows = []
    latencies = []
    for pid, p in pkts.items():
        inj = inject_times.get(pid, None)
        ej = eject_times.get(pid, None)
        rcvd = flits_rcvd.get(pid, 0)
        delivered = (rcvd == p["num_flits"])
        lat = (ej - inj) if (delivered and inj is not None and ej is not None) else None
        if lat is not None:
            latencies.append(lat)

        results_rows.append({
            "pkt_id": pid,
            "src_tile": p["src_tile"],
            "dst_tile": p["dst_tile"],
            "num_flits": p["num_flits"],
            "inject_cycle": inj if inj is not None else -1,
            "eject_cycle": ej if ej is not None else -1,
            "latency": lat if lat is not None else -1,
            "flits_delivered": rcvd,
            "status": "PASS" if delivered else "LOST"
        })

    with open(out_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=[
            "pkt_id", "src_tile", "dst_tile", "num_flits",
            "inject_cycle", "eject_cycle", "latency", "flits_delivered", "status"
        ])
        writer.writeheader()
        writer.writerows(results_rows)

    delivered_count = sum(1 for r in results_rows if r["status"] == "PASS")
    total_pkts = len(pkts)
    pdr = (delivered_count / total_pkts * 100.0) if total_pkts > 0 else 0.0
    avg_lat = (sum(latencies) / len(latencies)) if latencies else 0.0
    max_lat = max(latencies) if latencies else 0.0
    min_lat = min(latencies) if latencies else 0.0

    # Summary metrics
    total_cycles = cfg["cycles"] + max_wait
    throughput_flits = sum(r["flits_delivered"] for r in results_rows) / total_cycles

    summary_data = {
        "pattern": cfg["pattern"],
        "rate": cfg["rate"],
        "pkt_len": cfg["pkt_len"],
        "total_packets": total_pkts,
        "delivered_packets": delivered_count,
        "delivery_rate_pct": round(pdr, 2),
        "avg_latency": round(avg_lat, 2),
        "min_latency": min_lat,
        "max_latency": max_lat,
        "throughput_flits_per_cycle": round(throughput_flits, 4)
    }

    with open(summary_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(summary_data.keys()))
        writer.writeheader()
        writer.writerow(summary_data)

    print("\n=== Benchmark Results Summary ===")
    for k, v in summary_data.items():
        print(f"  {k}: {v}")
    print(f"Detailed results: {out_csv}")
    print(f"Summary saved: {summary_csv}")
    return True


def main():
    args = parse_args()
    success = run_benchmark(
        trace_path=args.trace,
        out_csv=args.out_csv,
        summary_csv=args.summary_csv,
        vcs_per_vn=args.vcs_per_vn,
        buffer_depth=args.buffer_depth,
        max_wait=args.max_wait
    )
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
